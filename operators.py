#Arithmetic Operators - simple calculations

x = 10
y = 5

print(x + y) #addition- sum
print(x - y) #subtraction
print(x * y) #multiplication
print(x / y) #division
print(x % y) #modulus-remainder after division



#Comparison Operators - compare values, return a boolean
num1 = 50
num2 = 67

print(num1 < num2)
print(num1 > num2)
print(num1 <= num2)
print(num1 >= num2)
print(num1 == num2) #equal to, using a singe = represents an assignment operator
print(num1 != num2)



#Assignment Operators - assign/ store values in variables
number = 10
print(number)

#operator precedence - order in which operations get executed
number += 2
print(number)


#Logical Operators - and , or, not
print(100 == 30 and 60 > 200 )
print(100 == 30 or 60 < 200 )
print( not (100 == 30 or 60 < 200 ))







